@dataclass
class LabelSet:
    key: str
    name: str
    description: str
    order: list[str]                      # display names, plotting order
    colors: dict[str, str]                # display name -> colour
    display: dict[str, str]               # code -> display name
    full_names: dict[str, str] = field(default_factory=dict)  # display name -> full name

    def show(self, code: str) -> str:
        return self.display.get(str(code), str(code))


@dataclass
class Dataset:
    key: str
    cfg: dict
    cells: pd.DataFrame
    qc_all: pd.DataFrame
    proteins: pd.DataFrame
    values: pd.DataFrame
    markers: pd.DataFrame
    presets: pd.DataFrame
    clusters: pd.DataFrame
    label_sets: dict[str, LabelSet]
    data_dir: Path
    build_info: dict

    @property
    def n_cells(self) -> int:
        return len(self.cells)

    def labels(self, key: str) -> pd.Series:
        """Display labels of every cell for one label set."""
        ls = self.label_sets[key]
        return self.cells[key].astype(str).map(ls.show)


@dataclass
class Comparison:
    """Data of the page that compares the conditions of one app (see ``configs/dct.yaml``)."""

    key: str
    cfg: dict                      # the app config's ``comparison`` block
    names: list[str]               # condition names, in the order of ``datasets``
    datasets: list[str]            # dataset keys
    suffixes: list[str]            # column suffix per condition (e.g. control, zero_k)
    proteins: pd.DataFrame         # proteins of either condition, with z-score parameters over both
    groups: list[dict]             # cell groups: key, name, label_set, values per condition, n_cells, reported
    reported_proteins: pd.DataFrame
    reported_panel: pd.DataFrame
    one_condition_only: pd.DataFrame
    data_dir: Path
    build_info: dict


def load_config(key: str) -> dict:
    return yaml.safe_load((CONFIG_DIR / f"{key}.yaml").read_text(encoding="utf-8"))


def types_key(ds_key: str, ls_key: str) -> str:
    """Session-state key of the sidebar cell-type filter (one per dataset and label set)."""
    return f"types__{ds_key}__{ls_key}"


def _label_sets(cfg: dict, cells: pd.DataFrame, labels_json: dict) -> dict[str, LabelSet]:
    out = {}
    for key, spec in cfg["label_sets"].items():
        info = labels_json[key]
        display = {str(k): str(v) for k, v in (spec.get("display") or {}).items()}
        cluster_of = spec.get("cluster_of")
        if cluster_of:
            parent = cfg["label_sets"][cluster_of].get("display") or {}
            display = {c: f"{c} · {parent.get(lab, lab)}" for c, lab in info["cluster_label"].items()}
        order = [display.get(str(c), str(c)) for c in info["order"]]
        if cluster_of:
            colors = {name: CLUSTER_PALETTE[i % len(CLUSTER_PALETTE)] for i, name in enumerate(order)}
        else:
            colors = {display.get(c, c): col for c, col in info["colors"].items()}
        full = {display.get(str(k), str(k)): v for k, v in (spec.get("full_names") or {}).items()}
        out[key] = LabelSet(key=key, name=spec["name"], description=spec.get("description", ""), order=order,
                            colors=colors, display=display, full_names=full)
    return out


@st.cache_resource(show_spinner="Loading data…")
def load_dataset(key: str) -> Dataset:
    cfg = load_config(key)
    data_dir = (APP_DIR / cfg["data_dir"]).resolve()
    read = lambda name: pd.read_parquet(data_dir / name)  # noqa: E731
    cells = read("cells.parquet")
    labels_json = json.loads((data_dir / "labels.json").read_text(encoding="utf-8"))
    build_info = json.loads((data_dir / "build_info.json").read_text(encoding="utf-8"))
    return Dataset(key=key, cfg=cfg, cells=cells, qc_all=read("cells_qc_all.parquet"),
                   proteins=read("proteins.parquet"), values=read("values.parquet"), markers=read("markers.parquet"),
                   presets=read("dotplot_presets.parquet"), clusters=read("clusters.parquet"),
                   label_sets=_label_sets(cfg, cells, labels_json), data_dir=data_dir, build_info=build_info)


@st.cache_data(show_spinner="Summarising proteins by cell type…")
def summary(key: str, label_set: str) -> pd.DataFrame:
    """Protein x group summary (display labels) for one label set; see compute.group_summary."""
    ds = load_dataset(key)
    out = compute.group_summary(ds.values, ds.proteins, ds.labels(label_set))
    order = {g: i for i, g in enumerate(ds.label_sets[label_set].order)}
    out["group_position"] = out["group"].map(order)
    return out.sort_values(["group_position", "protein_idx"]).reset_index(drop=True)


@st.cache_data
def protein_vector(key: str, protein_idx: int) -> np.ndarray:
    ds = load_dataset(key)
    return compute.protein_vector(ds.values, int(protein_idx), ds.n_cells)


@st.cache_resource(show_spinner="Loading comparison data…")
def load_comparison(app_key: str) -> Comparison:
    app = load_config(app_key)
    cfg = app["comparison"]
    conds = app["conditions"]
    data_dir = (APP_DIR / cfg["data_dir"]).resolve()
    read = lambda name: pd.read_parquet(data_dir / name)  # noqa: E731
    return Comparison(key=app_key, cfg=cfg, names=list(conds), datasets=list(conds.values()),
                      suffixes=list(cfg["suffixes"]), proteins=read("proteins.parquet"),
                      groups=json.loads((data_dir / "groups.json").read_text(encoding="utf-8")),
                      reported_proteins=read("reported_proteins.parquet"), reported_panel=read("reported_panel.parquet"),
                      one_condition_only=read("one_condition_only.parquet"), data_dir=data_dir,
                      build_info=json.loads((data_dir / "build_info.json").read_text(encoding="utf-8")))


def group_mask(ds: Dataset, label_set: str | None, values: list[str] | None) -> np.ndarray:
    """Cells of one comparison group in one dataset (all cells when the group uses no labels)."""
    if not label_set or values is None:
        return np.ones(ds.n_cells, dtype=bool)
    return ds.cells[label_set].astype(str).isin(values).to_numpy()


@st.cache_data(show_spinner="Comparing the two conditions…")
def comparison_table(app_key: str, group_key: str) -> pd.DataFrame:
    """One row per protein retained in both conditions, for one cell group: counts and summaries per
    condition (no test), plus the reported results where the group is the reported one."""
    cmp = load_comparison(app_key)
    group = next(g for g in cmp.groups if g["key"] == group_key)
    a, b = cmp.suffixes
    p = cmp.proteins[cmp.proteins["retained_in_both_conditions"]].reset_index(drop=True)
    out = p[["protein", "gene_symbol", "protein_group", "description"]].copy()
    side = {}
    for i, (key, suffix) in enumerate(zip(cmp.datasets, cmp.suffixes)):
        ds = load_dataset(key)
        mask = group_mask(ds, group["label_set"], group["values"][i])
        s = compute.detected_summary(ds.values, mask, len(ds.proteins))
        s.index = ds.proteins["protein"].to_numpy()
        side[suffix] = s.loc[out["protein"]].reset_index(drop=True)
        out[f"n_{suffix}"] = int(mask.sum())
    for suffix in cmp.suffixes:
        out[f"det_{suffix}"] = side[suffix]["n_detected"].to_numpy()
    for suffix in cmp.suffixes:
        out[f"detection_fraction_{suffix}"] = out[f"det_{suffix}"] / out[f"n_{suffix}"]
    out[f"detection_difference_{b}_minus_{a}"] = out[f"detection_fraction_{b}"] - out[f"detection_fraction_{a}"]
    for suffix in cmp.suffixes:
        out[f"median_ln_{suffix}"] = side[suffix]["median_ln1p_detected"].to_numpy()
    out["log2fc_detected"] = (side[b]["mean_ln1p_detected"].to_numpy() - side[a]["mean_ln1p_detected"].to_numpy()) / np.log(2)
    if group.get("reported"):
        cols = [c for c in cmp.cfg.get("reported_columns", []) if c in cmp.reported_proteins]
        out = out.merge(cmp.reported_proteins[["protein", *cols]], on="protein", how="left")
    return out


@st.cache_data(show_spinner="Summarising both conditions…")
def comparison_summary(app_key: str, label_sets: tuple[str, ...], protein_names: tuple[str, ...]) -> pd.DataFrame:
    """Group summaries of every condition for the given proteins (retained in both conditions).

    The z-score uses the per-protein mean and SD over the cells of both conditions, so the group means
    of the two conditions are on one scale. ``group`` is '<condition> · <label>'; ``protein_idx`` is the
    position in ``protein_names``.
    """
    cmp = load_comparison(app_key)
    both = cmp.proteins.set_index("protein")
    frames = []
    for name, key, ls_key in zip(cmp.names, cmp.datasets, label_sets):
        ds = load_dataset(key)
        idx = ds.proteins.set_index("protein")["protein_idx"].reindex(list(protein_names)).to_numpy(dtype=np.int64)
        prot = ds.proteins[["protein"]].copy()
        prot["ln1p_mean"] = prot["protein"].map(both["ln1p_mean_both"])
        prot["ln1p_sd"] = prot["protein"].map(both["ln1p_sd_both"])
        s = compute.group_summary(ds.values, prot, ds.labels(ls_key), protein_idx=idx)
        s["protein_idx"] = s["protein_idx"].map({int(i): n for n, i in enumerate(idx)})
        s["condition"], s["label"] = name, s["group"]
        s["group"] = name + " · " + s["group"]
        frames.append(s)
    return pd.concat(frames, ignore_index=True)


def search_frame(p: pd.DataFrame, field_key: str, term: str) -> pd.DataFrame:
    """Rows of a protein table whose chosen ID field contains ``term`` (case-insensitive); all rows if empty."""
    term = (term or "").strip().lower()
    if not term:
        return p
    if field_key == "gene":
        hay = p["gene_symbols_all"].str.lower() + ";" + p["protein"].str.lower()
    elif field_key == "accession":
        hay = p["protein_group"].str.lower()
    else:
        hay = p["description"].str.lower()
    return p[hay.str.contains(term, regex=False)]


def search_proteins(ds: Dataset, field_key: str, term: str) -> pd.DataFrame:
    """Proteins whose chosen ID field contains ``term`` (case-insensitive); all proteins if empty."""
    return search_frame(ds.proteins, field_key, term)


def protein_label(row) -> str:
    gene = row["gene_symbol"] or row["protein"]
    desc = row["description"]
    desc = desc if len(desc) <= 60 else desc[:57] + "…"
    return f"{gene} · {row['first_accession']} · {desc}"


def find_protein(ds: Dataset, text: str) -> int | None:
    """protein_idx from a URL value: protein name, gene symbol or accession (case-insensitive)."""
    t = str(text).strip().lower()
    if not t:
        return None
    p = ds.proteins
    for col in ("protein", "gene_symbol", "first_accession"):
        hit = p.index[p[col].str.lower() == t]
        if len(hit):
            return int(p.loc[hit[0], "protein_idx"])
    hit = p.index[p["protein_group"].str.lower().str.split(";").apply(lambda xs: t in [x.strip() for x in xs])]
    return int(p.loc[hit[0], "protein_idx"]) if len(hit) else None
