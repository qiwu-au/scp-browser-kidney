"""Entry point shared by the SCP browsers: page setup, sidebar and navigation.

Generated by Claude Code. Each browser is a thin entry file that calls ``run(<config name>)``.

A config either describes one dataset (``kidney.yaml``) or lists several conditions of one
experiment (``dct.yaml``: ``conditions`` maps a condition name to a dataset config). With
conditions, the sidebar gets a condition switch, every page shows the chosen condition on its own,
and a ``comparison`` block adds one page that compares the conditions.
"""

from __future__ import annotations

import streamlit as st

from . import pages
from .data import APP_DIR, CONFIG_DIR, ID_FIELDS, find_protein, load_config, load_dataset, types_key


@st.cache_resource(show_spinner=False)
def _loaded_state() -> dict:
    """One dict per server process: remembers which files the cached data were loaded from."""
    return {}


def _files_stamp() -> tuple:
    """Name, size and modification time of every config and data file of the app."""
    files = sorted(p for folder in (CONFIG_DIR, APP_DIR / "data") for p in folder.rglob("*") if p.is_file())
    return tuple((p.relative_to(APP_DIR).as_posix(), p.stat().st_size, p.stat().st_mtime_ns) for p in files)


def _refresh_caches() -> None:
    """Drop the cached data when a config or data file has changed since they were loaded.

    The data are cached for the lifetime of the server process. Without this check, a running app
    would keep showing the old data after its files were updated, until it is restarted.
    """
    stamp = _files_stamp()
    if _loaded_state().get("stamp") != stamp:
        st.cache_data.clear()
        st.cache_resource.clear()
        _loaded_state()["stamp"] = stamp


def _dataset_key(app_cfg: dict, app_key: str) -> str:
    """Dataset config shown in this run: the app's own, or the one of the chosen condition."""
    conds = app_cfg.get("conditions")
    if not conds:
        return app_key
    ss = st.session_state
    if ss.get("condition") not in conds:
        wanted = str(st.query_params.get("condition", "")).strip().lower()
        match = [name for name, key in conds.items() if wanted and wanted in (name.lower(), str(key).lower())]
        ss["condition"] = match[0] if match else next(iter(conds))
    return conds[ss["condition"]]


def _sidebar(ds, app_cfg: dict) -> None:
    cfg = ds.cfg
    with st.sidebar:
        conds = app_cfg.get("conditions")
        if conds:
            st.radio(app_cfg.get("condition_label", "Condition"), list(conds), key="condition", horizontal=True,
                     help=app_cfg.get("condition_help"))
        st.caption(f"**Dataset:** {cfg['dataset_label']} · {ds.n_cells:,} cells · {len(ds.proteins):,} proteins")
        keys = list(ds.label_sets)
        if len(keys) > 1:
            st.selectbox("Label set", keys, key="label_set", format_func=lambda k: ds.label_sets[k].name,
                         help="Cell grouping used by every plot and table.")
        ls = ds.label_sets[st.session_state["label_set"]]
        if ls.description:
            st.caption(ls.description)
        st.multiselect("Cell type(s)", ls.order, default=ls.order, key=types_key(ds.key, ls.key))
        st.selectbox("Protein ID field", list(ID_FIELDS), format_func=ID_FIELDS.get, key="id_field")
        st.text_input("Search term (contains)", key="search_term",
                      help="Filters the protein table and the protein pickers.")
        st.markdown("**Thresholds**")
        st.slider("Core detection in selected cell type (≥ Y%)", 0, 100, 50, 5, key="core_pct")
        st.slider("Max presence in other cell types (≤ X%)", 0, 100, 0, 5, key="unique_max_pct",
                  help="Unique proteins are Core in the chosen cell type and Core in ≤ this % of the other "
                       "selected cell types.")
        st.slider("UMAP size (px)", 400, 1200, 650, 50, key="umap_px")


def _sync_state(ds, app_key: str) -> None:
    """Session state for the dataset of this run (first run, or after the condition was switched)."""
    ss = st.session_state
    qp = st.query_params
    ss["app_key"] = app_key
    previous = ss.get("dataset_key")
    if previous != ds.key:
        if previous:
            # Condition switched: the chosen proteins follow by name (protein numbers differ between datasets).
            old = load_dataset(previous)
            for state_key in ("protein", "protein2"):
                idx = ss.get(state_key)
                ss[state_key] = find_protein(ds, old.proteins.loc[idx, "protein"]) if idx is not None else None
        ss["dataset_key"] = ds.key
    if ss.get("label_set") not in ds.label_sets:
        wanted = qp.get("labels")
        ss["label_set"] = wanted if wanted in ds.label_sets else ds.cfg["default_label_set"]
    ss.setdefault("id_field", "gene")
    if ss.get("protein") is None:
        idx = find_protein(ds, qp.get("protein", "")) if "protein" in qp else None
        ss["protein"] = idx if idx is not None else find_protein(ds, ds.cfg.get("default_protein", ""))


def run(config_key: str) -> None:
    app_cfg = load_config(config_key)
    st.set_page_config(page_title=app_cfg["short_title"], page_icon=app_cfg.get("page_icon", "🔬"), layout="wide")
    _refresh_caches()
    ds = load_dataset(_dataset_key(app_cfg, config_key))
    _sync_state(ds, config_key)
    _sidebar(ds, app_cfg)
    page_list = [
        st.Page(pages.overview, title="Overview", url_path="overview", default=True),
        st.Page(pages.proteins, title="Protein table", url_path="proteins"),
        st.Page(pages.protein_page, title="Protein page", url_path="protein"),
        st.Page(pages.cells_umap, title="Cells & UMAP", url_path="cells"),
        st.Page(pages.dotplot, title="Dotplot", url_path="dotplot"),
        st.Page(pages.core_unique, title="Core & unique", url_path="core-unique"),
        st.Page(pages.qc, title="Per-cell QC", url_path="qc"),
    ]
    if app_cfg.get("comparison"):
        page_list.append(st.Page(pages.compare, title=app_cfg["comparison"]["page_title"], url_path="compare"))
    page_list += [
        st.Page(pages.downloads, title="Downloads", url_path="downloads"),
        st.Page(pages.about, title="About", url_path="about"),
    ]
    nav = st.navigation(page_list)
    st.title(app_cfg["title"])
    nav.run()
