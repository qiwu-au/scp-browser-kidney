def _cmp_formats(columns, names: dict) -> dict:
    """Number formats of the comparison tables (keys = column names as shown)."""
    fmt = {names.get(c, c): st.column_config.NumberColumn(format="%.3f") for c in columns
           if c.startswith(("detection_", "median_ln_", "log2fc", "int_log2fc", "pseudobulk_", "score_coef"))}
    fmt.update({names.get(c, c): st.column_config.NumberColumn(format="%.2e") for c in columns if c.startswith(("q_", "p_"))})
    return fmt


def _cmp_one_protein(cmp, dsets: list[Dataset], group: dict, shared: pd.DataFrame) -> None:
    ss = st.session_state
    cfg = cmp.cfg
    a, b = cmp.suffixes
    hits = search_frame(shared, ss.get("id_field", "gene"), ss.get("search_term", ""))
    hits = hits.sort_values(["gene_symbol", "protein"], key=lambda s: s.str.lower())
    current_ds = load_dataset(ss["dataset_key"])
    current = current_ds.proteins.loc[ss["protein"], "protein"] if ss.get("protein") is not None else None
    options = hits["protein"].tolist()
    if current in set(shared["protein"]) and current not in options:
        options = [current] + options
    if not options:
        st.warning("No protein retained in both conditions matches the sidebar search.")
        return
    by_name = shared.set_index("protein", drop=False)
    term = (ss.get("search_term") or "").strip()
    st.caption(f"{len(hits):,} protein(s) retained in both conditions match the sidebar search"
               + (f" '{term}'" if term else "") + ".")

    def changed() -> None:
        idx = find_protein(current_ds, ss["cmp_protein"])
        if idx is not None:
            ss["protein"] = idx
            st.query_params["protein"] = ss["cmp_protein"]

    if ss.get("cmp_protein") not in options or (current in options and ss.get("cmp_protein") != current):
        ss.pop("cmp_protein", None)       # follow the protein chosen on the other pages
    index = options.index(current) if current in options else 0
    name = st.selectbox("Protein", options, index=index, key="cmp_protein", on_change=changed,
                        format_func=lambda n: protein_label(by_name.loc[n]))
    p = by_name.loc[name]
    accs = [x.strip() for x in p["protein_group"].split(";") if x.strip()]
    links = ", ".join(f"[{x}]({UNIPROT_URL.format(x)})" for x in accs[:6]) + (" …" if len(accs) > 6 else "")
    st.markdown(f"### {p['gene_symbol'] or name}\n{p['description']}\n\n**UniProt:** {links}")

    tbl = comparison_table(cmp.key, group["key"]).set_index("protein")
    row = tbl.loc[name]
    colors = dict(zip(cmp.names, cfg["colors"]))
    vals, masks, pidx = [], [], []
    for i, ds in enumerate(dsets):
        idx = find_protein(ds, name)
        mask = group_mask(ds, group["label_set"], group["values"][i])
        pidx.append(idx)
        masks.append(mask)
        vals.append(protein_vector(ds.key, idx))
    col1, col2 = st.columns(2)
    with col1:
        det = pd.DataFrame({"Condition": cmp.names,
                            "rate": [row[f"detection_fraction_{a}"], row[f"detection_fraction_{b}"]],
                            "label": [f"{int(row[f'det_{a}'])}/{int(row[f'n_{a}'])}", f"{int(row[f'det_{b}'])}/{int(row[f'n_{b}'])}"]})
        fig = px.bar(det, x="Condition", y="rate", color="Condition", color_discrete_map=colors, text="label",
                     category_orders={"Condition": cmp.names}, title="Cells with the protein detected",
                     labels={"rate": "Fraction of cells detected"})
        fig.update_traces(textposition="outside", cliponaxis=False)
        fig.update_layout(showlegend=False, margin=plots.MARGIN, template="plotly_white", yaxis_range=[0, 1.1])
        st.plotly_chart(fig, width="stretch")
    with col2:
        parts = []
        for cname, ds, v, mask in zip(cmp.names, dsets, vals, masks):
            keep = mask & ~np.isnan(v)
            parts.append(pd.DataFrame({"Condition": cname, "ln1p": np.log1p(v[keep]),
                                       "cell_id": ds.cells.loc[keep, "cell_id"].to_numpy()}))
        box = pd.concat(parts, ignore_index=True)
        if box.empty:
            st.info("Not detected in the cells of this group.")
        else:
            fig = px.box(box, x="Condition", y="ln1p", color="Condition", points="all", color_discrete_map=colors,
                         category_orders={"Condition": cmp.names}, hover_data=["cell_id"],
                         title="ln(1 + intensity), detected cells only", labels={"ln1p": "ln(1 + intensity)"})
            fig.update_layout(showlegend=False, margin=plots.MARGIN, template="plotly_white")
            st.plotly_chart(fig, width="stretch")

    m = st.columns(3)
    m[0].metric(f"Detection, {cmp.names[1]} − {cmp.names[0]}", f"{row[f'detection_difference_{b}_minus_{a}']:+.3f}")
    lfc = row["log2fc_detected"]
    m[1].metric("log2 fold change among detected cells", "—" if pd.isna(lfc) else f"{lfc:+.2f}",
                help="Difference of the mean ln(1 + intensity) among the cells with the protein detected, "
                     f"{cmp.names[1]} minus {cmp.names[0]}, in log2 units. No adjustment and no test.")
    m[2].metric(f"Median ln(1 + intensity), {cmp.names[0]} | {cmp.names[1]}",
                " | ".join("—" if pd.isna(row[f"median_ln_{s}"]) else f"{row[f'median_ln_{s}']:.2f}" for s in cmp.suffixes))

    if group.get("reported"):
        st.markdown(f"#### {cfg['reported_title']}")
        rep = cmp.reported_proteins.set_index("protein")
        if name in rep.index:
            shown = [c for c in cfg.get("reported_columns", []) if c in rep.columns]
            names = cfg.get("column_names", {})
            st.dataframe(rep.loc[[name], shown].rename(columns=names), hide_index=True, width="stretch",
                         column_config=_cmp_formats(shown, names))
            st.caption(cfg["reported_note"])
        else:
            st.caption(cfg["not_tested_note"])

    st.markdown("#### UMAP overlay, each condition on its own UMAP")
    mode, clip = overlay_controls("cmp")
    crange = None
    if mode != "binary":
        pooled = np.concatenate([plots.overlay_values(v[mask], mode) for v, mask in zip(vals, masks)])
        if len(pooled):
            crange = (float(pooled.min()), float(np.percentile(pooled, clip)) if clip else float(pooled.max()))
    size = min(int(ss["umap_px"]), 560)
    cols = st.columns(len(dsets))
    for col, cname, ds, v, mask in zip(cols, cmp.names, dsets, vals, masks):
        with col:
            df = _cmp_overlay_frame(ds, mask, cfg.get("hover_label_set", ds.cfg["default_label_set"]))
            xr, yr = plots.square_ranges(ds.cells["UMAP1"].to_numpy(), ds.cells["UMAP2"].to_numpy())
            n_det = int((~np.isnan(v[mask])).sum())
            fig = plots.umap_overlay(df, v[mask], mode, clip, xr, yr, size,
                                     f"{cname}: detected in {n_det} of {int(mask.sum())} cells", crange=crange)
            st.plotly_chart(fig, width="stretch")
    if crange is not None:
        st.caption("Both plots use one colour range.")


