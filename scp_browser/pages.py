def qc_table(ds: Dataset) -> pd.DataFrame:
    """All raw cells: filter metrics for every cell, retained-cell metrics and labels where retained."""
    keep_cols = ["cell_id", *ds.label_sets, *ds.cfg.get("qc_metrics", {})]
    retained = ds.cells[[k for k in keep_cols if k in ds.cells]].copy()
    for k, ls in ds.label_sets.items():
        retained[k] = retained[k].astype(str).map(ls.show)
    return ds.qc_all.merge(retained, on="cell_id", how="left")


