@dataclass
class Ctx:
    ds: Dataset
    ls: LabelSet
    types: list[str]          # selected groups, plotting order
    labels: pd.Series         # display label per cell
    keep: np.ndarray          # cells in the selected groups

    @property
    def summary(self) -> pd.DataFrame:
        return summary(self.ds.key, self.ls.key)


def ctx() -> Ctx:
    ss = st.session_state
    ds = load_dataset(ss["dataset_key"])
    ls = ds.label_sets[ss["label_set"]]
    chosen = set(ss.get(types_key(ds.key, ls.key), ls.order))
    types = [t for t in ls.order if t in chosen]
    labels = ds.labels(ls.key)
    return Ctx(ds=ds, ls=ls, types=types, labels=labels, keep=labels.isin(types).to_numpy())


def help_box(title: str, text: str) -> None:
    with st.expander(f"Help — {title}", expanded=False):
        st.markdown(text)


def csv_bytes(frame: pd.DataFrame) -> bytes:
    buf = io.StringIO()
    frame.to_csv(buf, index=False)
    return buf.getvalue().encode("utf-8")


def need_types(c: Ctx) -> bool:
    if not c.types:
        st.info("No cell type selected in the sidebar.")
        return False
    return True


def umap_frame(c: Ctx) -> pd.DataFrame:
    cells = c.ds.cells
    df = pd.DataFrame({"cell_id": cells["cell_id"], "UMAP1": cells["UMAP1"], "UMAP2": cells["UMAP2"],
                       "Cell type": c.labels})
    df["hover"] = df["cell_id"] + "<br>" + df["Cell type"]
    return df


def axis_ranges(c: Ctx):
    # Fixed to all cells, so filtered views and overlays share the same frame.
    return plots.square_ranges(c.ds.cells["UMAP1"].to_numpy(), c.ds.cells["UMAP2"].to_numpy())


def protein_picker(c: Ctx, key: str, label: str = "Protein", state_key: str = "protein",
                   sync_url: bool = True) -> int | None:
    """Selectbox over the proteins matching the sidebar search; the choice is shared across pages."""
    ss = st.session_state
    hits = search_proteins(c.ds, ss.get("id_field", "gene"), ss.get("search_term", ""))
    hits = hits.sort_values(["gene_symbol", "protein"], key=lambda s: s.str.lower())
    options = hits["protein_idx"].tolist()
    current = ss.get(state_key)
    if current is not None and current not in options:
        options = [current] + options
    if not options:
        st.warning("No protein matches the sidebar search.")
        return None
    by_idx = c.ds.proteins.set_index("protein_idx")
    term = (ss.get("search_term") or "").strip()
    st.caption(f"{len(hits):,} protein(s) match the sidebar search" + (f" '{term}'" if term else "") + ".")
    wkey = f"{key}__{c.ds.key}"          # one widget per dataset: protein numbers differ between datasets

    def changed() -> None:
        ss[state_key] = ss[wkey]
        if sync_url and ss[wkey] is not None:
            st.query_params["protein"] = by_idx.loc[ss[wkey], "protein"]

    index = options.index(current) if current in options else None
    if index is None and len(options) == 1:
        index = 0
        ss[state_key] = options[0]
    return st.selectbox(label, options, index=index, key=wkey, on_change=changed,
                        format_func=lambda i: protein_label(by_idx.loc[i]), placeholder="Choose a protein")


def overlay_controls(key: str) -> tuple[str, float | None]:
    col1, col2 = st.columns([3, 2])
    with col1:
        mode = st.radio("Colour", ["ln", "raw", "binary"], horizontal=True, key=f"{key}_mode",
                        format_func={"ln": "ln(1 + intensity)", "raw": "Intensity", "binary": "Detected / not"}.get)
    with col2:
        clip = st.toggle("Clip colour at 99th percentile", value=True, key=f"{key}_clip",
                         disabled=mode == "binary")
    return mode, (99.0 if clip and mode != "binary" else None)


def overlay_figure(c: Ctx, pidx: int, mode: str, clip: float | None, title: str | None = None):
    df = umap_frame(c)
    vals = protein_vector(c.ds.key, pidx)
    df, vals = df[c.keep], vals[c.keep]
    name = c.ds.proteins.loc[pidx, "gene_symbol"] or c.ds.proteins.loc[pidx, "protein"]
    xr, yr = axis_ranges(c)
    n_det = int((~np.isnan(vals)).sum())
    fig = plots.umap_overlay(df, vals, mode, clip, xr, yr, st.session_state["umap_px"],
                             title or f"{name}: detected in {n_det} of {len(vals)} shown cells")
    return fig, n_det, len(vals)


