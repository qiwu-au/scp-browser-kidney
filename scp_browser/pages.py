def overview() -> None:
    c = ctx()
    ds, cfg = c.ds, c.ds.cfg
    st.markdown(cfg.get("intro", ""))
    m = st.columns(4)
    m[0].metric("Cells (retained)", f"{ds.n_cells:,}")
    m[1].metric("Proteins", f"{len(ds.proteins):,}")
    m[2].metric(f"Groups ({c.ls.name})", len(c.ls.order))
    m[3].metric("Median proteins per cell", f"{int(ds.cells['n_proteins'].median()):,}")
    if not need_types(c):
        return

    st.subheader("Mean detection rate by cell type")
    help_box("Overview", "**Bar chart** of the *mean detection rate by cell type*.\n\n"
             "- A protein's **detection rate** in a cell type = cells with intensity > 0 ÷ cells of that type.\n"
             "- Each bar is the **mean of these rates over all proteins**.\n"
             "- The sidebar **Cell type(s)** filter applies.")
    s = c.summary
    s = s[s["group"].isin(c.types)]
    mean_det = s.groupby("group", sort=False)["detection_rate"].mean().reindex(c.types).reset_index()
    fig = px.bar(mean_det, x="group", y="detection_rate", color="group", color_discrete_map=c.ls.colors,
                 category_orders={"group": c.types},
                 labels={"group": "Cell type", "detection_rate": "Mean detection rate (fraction of cells)"})
    fig.update_layout(showlegend=False, margin=plots.MARGIN, template="plotly_white")
    st.plotly_chart(fig, width="stretch")

    st.subheader("Cells per cell type")
    counts = c.labels[c.keep].value_counts().reindex(c.types).rename_axis("Cell type").reset_index(name="Cells")
    if c.ls.full_names:
        counts.insert(1, "Full name", counts["Cell type"].map(c.ls.full_names).fillna(""))
    st.dataframe(counts, hide_index=True, width="stretch")

    cross = cfg.get("crosstab")
    if cross:
        # One pair [rows, columns] of label sets, or a list of such pairs.
        pairs = cross if isinstance(cross[0], (list, tuple)) else [cross]
        st.subheader("How the label sets relate")
        help_box("Label crosstab", "Number of cells for each pair of labels: " + "; ".join(
                 f"rows = **{ds.label_sets[r].name}**, columns = **{ds.label_sets[k].name}**" for r, k in pairs)
                 + ". All retained cells are counted (the sidebar filter does not apply).")
        for rows_key, cols_key in pairs:
            a, b = ds.label_sets[rows_key], ds.label_sets[cols_key]
            tab = pd.crosstab(ds.labels(a.key), ds.labels(b.key)).reindex(index=a.order, columns=b.order, fill_value=0)
            tab.index.name, tab.columns.name = a.name, b.name
            fig = px.imshow(tab, text_auto=True, color_continuous_scale=plots.BLUE_SCALE, aspect="auto",
                            labels=dict(x=b.name, y=a.name, color="Cells"))
            fig.update_layout(margin=plots.MARGIN, height=max(320, 34 * len(a.order) + 140))
            st.plotly_chart(fig, width="stretch")

    if len(ds.clusters) and "cluster_table" in cfg:
        st.subheader(cfg["cluster_table"]["title"])
        help_box("Cluster evidence", cfg["cluster_table"]["help"])
        lab = cfg["cluster_table"]["label_set"]
        names = cfg["cluster_table"].get("columns") or {c: c for c in ds.clusters.columns}
        tbl = ds.clusters[[c for c in names if c in ds.clusters.columns]].copy()
        for col in [lab, *cfg["cluster_table"].get("display_columns", [])]:
            if col in tbl:
                tbl[col] = tbl[col].astype(str).map(ds.label_sets[lab].show)
        st.dataframe(tbl.rename(columns=names), hide_index=True, width="stretch")


