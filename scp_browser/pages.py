def cells_umap() -> None:
    c = ctx()
    ds = c.ds
    st.subheader("Cells / UMAP")
    help_box("Cells / UMAP", "**Figure**: UMAP of the retained cells (the stored embedding of the neighbour "
             "graph), coloured by cell type or by a per-cell QC value. Hover shows "
             "the cell ID. Axes are square and fixed to all cells, so filtered views stay comparable; adjust the "
             "size in the sidebar.\n\n**Table**: UMAP coordinates with the per-cell labels.")
    if not need_types(c):
        return
    qc_opts = ds.cfg.get("qc_metrics", {})
    colour_by = st.selectbox("Colour cells by", ["__labels__", *qc_opts],
                             format_func=lambda k: c.ls.name if k == "__labels__" else qc_opts[k], key="umap_colour")
    df = umap_frame(c)
    for col in qc_opts:
        df[qc_opts[col]] = ds.cells[col].to_numpy()
    df = df[c.keep]
    xr, yr = axis_ranges(c)
    size = st.session_state["umap_px"]
    if colour_by == "__labels__":
        fig = plots.umap_categorical(df, "Cell type", c.types, c.ls.colors, xr, yr, size, f"UMAP: {c.ls.name}",
                                     ["cell_id"])
    else:
        fig = plots.umap_continuous(df, qc_opts[colour_by], xr, yr, size, f"UMAP: {qc_opts[colour_by]}",
                                    ["cell_id", "Cell type"], qc_opts[colour_by])
    st.plotly_chart(fig, width="stretch")

    st.markdown("### UMAP overlay by protein abundance")
    help_box("Overlay", "The protein list follows the sidebar **Protein ID field** and **Search term**. Colour: "
             "ln(1+intensity), intensity, or detected / not detected; clipping at the 99th percentile stops a few "
             "bright cells from setting the colour scale. The protein chosen here is also shown on the Protein page.")
    pidx = protein_picker(c, "cells_pick")
    if pidx is not None:
        mode, clip = overlay_controls("cells")
        fig, n_det, n = overlay_figure(c, pidx, mode, clip)
        st.caption(f"overlay cells = {n}, detected = {n_det}, not detected = {n - n_det}")
        st.plotly_chart(fig, width="stretch")

    st.markdown("### Cell table")
    cols = ["cell_id", "UMAP1", "UMAP2", *ds.label_sets]
    extra = [k for k in ds.cfg.get("cell_extra_columns", []) if k in ds.cells]
    tbl = ds.cells.loc[c.keep, cols + extra].copy()
    for k, ls in ds.label_sets.items():
        tbl[k] = tbl[k].astype(str).map(ls.show)
    st.dataframe(tbl.rename(columns={k: ls.name for k, ls in ds.label_sets.items()}), hide_index=True,
                 width="stretch", height=380)


