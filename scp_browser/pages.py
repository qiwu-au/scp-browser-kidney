def _cmp_dotplot(cmp, dsets: list[Dataset], shared: pd.DataFrame) -> None:
    cfg = cmp.cfg
    row_sets = cfg["row_sets"]
    choice = st.selectbox("Rows", range(len(row_sets)), format_func=lambda i: row_sets[i]["name"], key="cmp_rows")
    label_sets = tuple(row_sets[choice]["label_sets"])
    source = st.radio("Columns", ["preset", "custom"], horizontal=True, key="cmp_dot_source",
                      format_func={"preset": "Preset", "custom": "Your list"}.get)
    in_both = set(shared["protein"])
    groups = None
    if source == "preset":
        presets = dsets[0].presets
        name = st.selectbox("Preset", list(dict.fromkeys(presets["preset"])), key="cmp_dot_preset")
        pre = presets[(presets["preset"] == name) & presets["protein"].isin(in_both)].sort_values("position")
        proteins, groups = pre["protein"].tolist(), pre["group"].tolist()
    else:
        text_in = st.text_area("Proteins", value=dsets[0].cfg.get("default_dotplot_list", ""), key="cmp_dot_custom", height=90)
        proteins, missing = [], []
        lookup = {str(v).lower(): n for col in ("first_accession", "gene_symbol", "protein")
                  for n, v in zip(shared["protein"], shared[col])}
        for tok in [t for t in TOKEN_SPLIT.split(text_in) if t]:
            hit = lookup.get(tok.lower())
            (missing.append(tok) if hit is None else proteins.append(hit))
        proteins = list(dict.fromkeys(proteins))
        if missing:
            st.warning("Not among the proteins retained in both conditions: " + ", ".join(missing))
    if not proteins:
        st.info("No proteins to plot.")
        return
    s = comparison_summary(cmp.key, label_sets, tuple(proteins))
    # Rows: the same label of the two conditions next to each other.
    labels = list(dict.fromkeys(g for ds, ls in zip(dsets, label_sets) for g in ds.label_sets[ls].order))
    present = set(s["group"])
    rows = [f"{cname} · {lab}" for lab in labels for cname in cmp.names if f"{cname} · {lab}" in present]
    tbl = compute.dotplot_table(s, rows, list(range(len(proteins))))
    by_name = shared.set_index("protein")
    tick = {i: (by_name.loc[n, "gene_symbol"] or n) for i, n in enumerate(proteins)}
    tbl["column_key"], tbl["tick"] = tbl["protein_idx"], tbl["protein_idx"].map(tick)
    fig = plots.dotplot(tbl, rows, [(i, tick[i]) for i in range(len(proteins))],
                        f"{row_sets[choice]['name']}: {len(proteins)} proteins", groups)
    st.plotly_chart(fig, width="content")
    out = tbl[["condition", "label", "tick", "n_cells", "n_detected", "detection_rate", "mean_ln1p", "mean_z", "scaled_0_1"]]
    out = out.rename(columns={"label": "cell_type", "tick": "protein"})
    st.download_button("Download dotplot values (CSV)", csv_bytes(out),
                       file_name=f"{cfg['download_prefix']}_comparison_dotplot_values.csv", mime="text/csv")
    with st.expander("Values"):
        st.dataframe(out, hide_index=True, width="stretch")


