def protein_page() -> None:
    c = ctx()
    st.subheader("Protein page")
    help_box("Protein page", "One protein across cell types.\n\n"
             "- Pick a protein (the list follows the sidebar search). The page address gets `?protein=<name>`, so "
             "the view can be shared or linked (gene symbol, analysis name or UniProt accession all work).\n"
             "- **Detection rate** by cell type, and **ln(1+intensity)** of the cells where it is detected.\n"
             "- **UMAP overlay**: not-detected cells grey; detected cells coloured by ln(1+intensity) (default), "
             "intensity, or detected / not detected. Clipping at the 99th percentile stops a few bright cells "
             "from setting the colour scale.\n"
             "- **Compare with a second protein** draws a second overlay next to the first.")
    pidx = protein_picker(c, "protein_page_pick")
    if pidx is None or not need_types(c):
        return
    p = c.ds.proteins.loc[pidx]
    accs = [a.strip() for a in p["protein_group"].split(";") if a.strip()]
    links = ", ".join(f"[{a}]({UNIPROT_URL.format(a)})" for a in accs[:6]) + (" …" if len(accs) > 6 else "")
    st.markdown(f"### {p['gene_symbol'] or p['protein']}\n{p['description']}")
    info = st.columns(3)
    info[0].metric("Detected in (retained cells)", f"{p['n_cells_detected']} / {c.ds.n_cells}")
    info[1].markdown(f"**UniProt:** {links}\n\n**Analysis name:** `{p['protein']}`")
    info[2].markdown("**Listed as marker for:** " + (p["marker_for"].replace(";", ", ") or "—")
                     + "\n\n" + f"**Link:** `?protein={p['protein']}`")

    s = c.summary
    s = s[(s["protein_idx"] == pidx) & s["group"].isin(c.types)].copy()
    s["label"] = s["n_detected"].astype(str) + "/" + s["n_cells"].astype(str)
    col1, col2 = st.columns(2)
    with col1:
        fig = px.bar(s, x="group", y="detection_rate", color="group", color_discrete_map=c.ls.colors, text="label",
                     category_orders={"group": c.types}, title="Detection rate by cell type",
                     labels={"group": "Cell type", "detection_rate": "Fraction of cells detected"})
        fig.update_traces(textposition="outside", textangle=0, cliponaxis=False)
        fig.update_layout(showlegend=False, margin=plots.MARGIN, template="plotly_white", yaxis_range=[0, 1.1])
        st.plotly_chart(fig, width="stretch")
    with col2:
        vals = protein_vector(c.ds.key, pidx)
        det = pd.DataFrame({"group": c.labels, "ln1p": np.log1p(vals), "cell_id": c.ds.cells["cell_id"]})
        det = det[c.keep & ~np.isnan(vals)]
        if det.empty:
            st.info("Not detected in the selected cell types.")
        else:
            fig = px.box(det, x="group", y="ln1p", color="group", points="all", color_discrete_map=c.ls.colors,
                         category_orders={"group": c.types}, hover_data=["cell_id"],
                         title="ln(1 + intensity), detected cells only",
                         labels={"group": "Cell type", "ln1p": "ln(1 + intensity)"})
            fig.update_layout(showlegend=False, margin=plots.MARGIN, template="plotly_white")
            st.plotly_chart(fig, width="stretch")

    st.markdown("#### UMAP overlay")
    mode, clip = overlay_controls("protein_page")
    second = st.toggle("Compare with a second protein", key="protein_page_compare")
    if second:
        p2 = protein_picker(c, "protein_page_pick2", "Second protein", state_key="protein2", sync_url=False)
        cols = st.columns(2)
        with cols[0]:
            fig, _, _ = overlay_figure(c, pidx, mode, clip)
            st.plotly_chart(fig, width="stretch")
        with cols[1]:
            if p2 is None:
                st.info("Choose a second protein above.")
            else:
                fig, _, _ = overlay_figure(c, p2, mode, clip)
                st.plotly_chart(fig, width="stretch")
    else:
        fig, _, _ = overlay_figure(c, pidx, mode, clip)
        st.plotly_chart(fig, width="stretch")


