def text(cfg: dict, key: str) -> str:
    return (cfg.get("texts") or {}).get(key, DEFAULT_TEXTS[key])


def file_prefix(ds: Dataset) -> str:
    """Start of the download file names of a dataset."""
    return ds.cfg.get("download_prefix", ds.key)


def app_config(ds: Dataset) -> dict:
    """Config of the running app (the dataset's own config, or the config that lists it as a condition)."""
    return load_config(st.session_state.get("app_key", ds.key))


