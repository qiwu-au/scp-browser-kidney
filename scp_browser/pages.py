def core_unique() -> None:
    c = ctx()
    ss = st.session_state
    st.subheader("Core & Unique proteins by cell type")
    help_box("Core & Unique", "**Tabs**:\n"
             "- **Core (≥ Y%)**: proteins detected in at least **Y%** of the chosen cell type's cells.\n"
             "- **Unique by % (≤ X%)**: Core proteins that are also Core in **≤ X%** of the other selected cell "
             "types (other types where the protein is Core ÷ number of other selected types).\n\n"
             "Set **Y** and **X** in the sidebar *Thresholds*. Each list can be downloaded.")
    if not need_types(c):
        return
    chosen = st.selectbox("Cell type", c.types, key=f"core_type__{c.ds.key}__{c.ls.key}")
    core, uniq, n_other = compute.core_unique(c.summary, c.types, chosen, ss["core_pct"] / 100.0, ss["unique_max_pct"])
    p = c.ds.proteins.set_index("protein_idx")
    s = c.summary
    rate = s[s["group"] == chosen].set_index("protein_idx")["detection_rate"]

    def table(idx) -> pd.DataFrame:
        return pd.DataFrame({ID_FIELDS["accession"]: p.loc[idx, "protein_group"].to_numpy(),
                             ID_FIELDS["gene"]: p.loc[idx, "gene_symbol"].to_numpy(),
                             ID_FIELDS["description"]: p.loc[idx, "description"].to_numpy(),
                             f"Detection rate in {chosen}": rate.reindex(idx).to_numpy()})

    tab_core, tab_uniq = st.tabs([f"Core (≥ {ss['core_pct']}%)", f"Unique by % (≤ {ss['unique_max_pct']}% in other types)"])
    with tab_core:
        t = table(core)
