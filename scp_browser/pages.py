def protein_rows(c: Ctx, detected_only: bool = True) -> pd.DataFrame:
    s = c.summary
    s = s[s["group"].isin(c.types)]
    if detected_only:
        s = s[s["n_detected"] > 0]
    ss = st.session_state
    hits = search_proteins(c.ds, ss.get("id_field", "gene"), ss.get("search_term", ""))
    s = s[s["protein_idx"].isin(hits["protein_idx"])]
    p = c.ds.proteins.set_index("protein_idx")
    out = pd.DataFrame({
        ID_FIELDS["gene"]: p.loc[s["protein_idx"], "gene_symbol"].to_numpy(),
        "Cell type": s["group"].to_numpy(),
        "Detection rate": s["detection_rate"].to_numpy(),
        "n detected": s["n_detected"].to_numpy(),
        "n cells": s["n_cells"].to_numpy(),
        "Median intensity (detected)": s["median_intensity"].to_numpy(),
        "Mean ln(1+intensity)": s["mean_ln1p"].to_numpy(),
        text(c.ds.cfg, "marker_column"): p.loc[s["protein_idx"], "marker_for"].to_numpy(),
        ID_FIELDS["accession"]: p.loc[s["protein_idx"], "protein_group"].to_numpy(),
        ID_FIELDS["description"]: p.loc[s["protein_idx"], "description"].to_numpy(),
        "Protein (analysis name)": p.loc[s["protein_idx"], "protein"].to_numpy(),
    })
    return out


def proteins() -> None:
    c = ctx()
    st.subheader("Proteins by cell type")
    help_box("Protein table", "**Table**: protein × cell type summary; rows where the protein is not detected in "
             "that cell type are left out.\n\n"
             "- **Detection rate**: fraction of the cell type's cells with intensity > 0.\n"
             "- **Median intensity**: median of the intensities in the detected cells.\n"
             "- **Mean ln(1+intensity)**: mean over all cells of the type, not-detected cells counted as 0.\n"
             "- **n detected / n cells**: detected cells / all cells of the type.\n"
             f"- **Marker for**: {text(c.ds.cfg, 'marker_help')}.\n"
             "- Use the sidebar **Protein ID field** and **Search term** to filter; click a column header to sort.")
    if not need_types(c):
        return
    tbl = protein_rows(c)
    st.caption(f"{tbl.shape[0]:,} rows · {tbl[ID_FIELDS['accession']].nunique():,} proteins")
    st.dataframe(tbl, hide_index=True, width="stretch", height=560,
                 column_config={"Detection rate": st.column_config.NumberColumn(format="%.3f"),
                                "Median intensity (detected)": st.column_config.NumberColumn(format="%.1f"),
                                "Mean ln(1+intensity)": st.column_config.NumberColumn(format="%.3f")})
    st.download_button("Download this table (CSV)", csv_bytes(tbl),
                       file_name=f"{file_prefix(c.ds)}_protein_table_filtered.csv", mime="text/csv")


