TOKEN_SPLIT = re.compile(r"[\s,;]+")


def dotplot() -> None:
    c = ctx()
    ds, cfg = c.ds, c.ds.cfg
    st.subheader("Dotplot builder")
    help_box("Dotplot", "Dot **size** = fraction of the cell type's cells where the protein is detected; "
             "dot **colour** = cell-type mean of the per-protein z-scored ln(1+intensity), rescaled 0–1 per protein "
             "across the plotted rows (the encoding of the manuscript's marker dotplot). Rows follow the sidebar "
             "cell-type filter.\n\n"
             f"- **Presets**: {text(cfg, 'dotplot_presets_help')}.\n"
             "- **Your list**: gene symbols, analysis names or UniProt accessions, separated by commas, spaces or "
             "new lines. Entries not found among the proteins are listed.")
    if not need_types(c):
        return
    source = st.radio("Columns", ["preset", "custom"], horizontal=True, key="dot_source",
                      format_func={"preset": "Preset", "custom": "Your list"}.get)
    groups = None
    if source == "preset":
        names = list(dict.fromkeys(ds.presets["preset"]))
        name = st.selectbox("Preset", names, key=f"dot_preset__{ds.key}")
        pre = ds.presets[ds.presets["preset"] == name].sort_values("position")
        pidx_map = ds.proteins.set_index("protein")["protein_idx"]
        pidx = pre["protein"].map(pidx_map).astype(int).tolist()
        shown_with = (cfg.get("preset_group_label_set") or {}).get(name)
        groups = [ds.label_sets[shown_with].show(g) if shown_with else g for g in pre["group"]]
    else:
        typed = st.text_area("Proteins", value=cfg.get("default_dotplot_list", ""), key="dot_custom", height=90)
        pidx, missing = [], []
        for tok in [t for t in TOKEN_SPLIT.split(typed) if t]:
            i = find_protein(ds, tok)
            (missing.append(tok) if i is None else pidx.append(i))
        pidx = list(dict.fromkeys(pidx))
        if missing:
            st.warning("Not among the proteins of this dataset: " + ", ".join(missing))
    if not pidx:
        st.info("No proteins to plot.")
        return

    s = c.summary
    tbl = compute.dotplot_table(s, c.types, pidx)
    p = ds.proteins.set_index("protein_idx")
    tick = {i: (p.loc[i, "gene_symbol"] or p.loc[i, "protein"]) for i in pidx}
    tbl["column_key"], tbl["tick"] = tbl["protein_idx"], tbl["protein_idx"].map(tick)
    columns = [(i, tick[i]) for i in pidx]
    fig = plots.dotplot(tbl, c.types, columns, f"{c.ls.name}: {len(pidx)} proteins", groups)
    st.plotly_chart(fig, width="content")
    out = tbl[["group", "tick", "n_cells", "n_detected", "detection_rate", "mean_ln1p", "mean_z", "scaled_0_1"]]
    out = out.rename(columns={"group": "cell_type", "tick": "protein"})
    st.download_button("Download dotplot values (CSV)", csv_bytes(out),
                       file_name=f"{file_prefix(ds)}_dotplot_values.csv", mime="text/csv")
    with st.expander("Values"):
        st.dataframe(out, hide_index=True, width="stretch")


