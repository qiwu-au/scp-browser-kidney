"""Summaries computed from the browser data (pandas / numpy only).

Generated by Claude Code. The app and the checks of the data build scripts both use
these functions, so the numbers shown in the browser are the ones checked
against the analysis tables.

Data layout (see the data dictionary):
- ``values``: detected entries only, one row per (protein_idx, cell_idx) with
  ``intensity`` > 0. Every other (protein, cell) pair is "not detected".
- ``cells``: one row per retained cell, row position = ``cell_idx``.
- ``proteins``: one row per retained protein, row position = ``protein_idx``,
  with ``ln1p_mean`` and ``ln1p_sd`` (over all cells, zeros included) for the
  per-protein z-score used by the dotplots (as ``sc.pp.scale``, clipped at 10).
"""

from __future__ import annotations

import warnings

import numpy as np
import pandas as pd

Z_CLIP = 10.0


def zscore_params(proteins: pd.DataFrame) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Per-protein mean, SD (zero SD -> 1) and the clipped z of a not-detected entry."""
    mu = proteins["ln1p_mean"].to_numpy(dtype=np.float64)
    sd = proteins["ln1p_sd"].to_numpy(dtype=np.float64)
    sd = np.where(sd == 0, 1.0, sd)
    z0 = np.clip(-mu / sd, -Z_CLIP, Z_CLIP)
    return mu, sd, z0


def group_summary(values: pd.DataFrame, proteins: pd.DataFrame, groups: pd.Series,
                  protein_idx: np.ndarray | None = None) -> pd.DataFrame:
    """Per (group, protein) summary over the cells of each group.

    ``groups`` holds one label per cell (position = cell_idx); cells with a
    missing label are left out. Returns every (group, protein) pair, including
    proteins not detected in a group, with:
    n_cells, n_detected, detection_rate, median_intensity (detected cells only),
    mean_ln1p (ln(1 + intensity) averaged over all cells of the group, zeros
    included) and mean_z (the per-protein z-score averaged the same way).
    """
    labels = pd.Series(groups).reset_index(drop=True)
    keep = labels.notna().to_numpy()
    codes, names = pd.factorize(labels[keep].astype(str), sort=False)
    cell_group = np.full(len(labels), -1, dtype=np.int64)
    cell_group[np.flatnonzero(keep)] = codes
    n_cells = np.bincount(codes, minlength=len(names))

    mu, sd, z0 = zscore_params(proteins)
    pidx = np.arange(len(proteins)) if protein_idx is None else np.asarray(protein_idx, dtype=np.int64)

    v = values
    if protein_idx is not None:
        v = v[v["protein_idx"].isin(pidx)]
    g = cell_group[v["cell_idx"].to_numpy()]
    v = v.loc[g >= 0]
    g = g[g >= 0]
    p = v["protein_idx"].to_numpy()
    intensity = v["intensity"].to_numpy(dtype=np.float64)
    ln1p = np.log1p(intensity)
    z = np.clip((ln1p - mu[p]) / sd[p], -Z_CLIP, Z_CLIP)
    det = pd.DataFrame({"g": g, "p": p, "intensity": intensity, "ln1p": ln1p, "z": z})
    agg = det.groupby(["g", "p"], sort=False).agg(
        n_detected=("intensity", "size"), median_intensity=("intensity", "median"),
        sum_ln1p=("ln1p", "sum"), sum_z=("z", "sum"))

    grid = pd.MultiIndex.from_product([np.arange(len(names)), pidx], names=["g", "p"])
    out = agg.reindex(grid).reset_index()
    out["n_detected"] = out["n_detected"].fillna(0).astype(np.int64)
    out["n_cells"] = n_cells[out["g"].to_numpy()]
    out["detection_rate"] = out["n_detected"] / out["n_cells"]
    out["mean_ln1p"] = out["sum_ln1p"].fillna(0.0) / out["n_cells"]
    n_missing = out["n_cells"] - out["n_detected"]
    out["mean_z"] = (out["sum_z"].fillna(0.0) + n_missing * z0[out["p"].to_numpy()]) / out["n_cells"]
    out["group"] = np.asarray(names, dtype=object)[out["g"].to_numpy()]
    out = out.rename(columns={"p": "protein_idx"})
    return out[["group", "protein_idx", "n_cells", "n_detected", "detection_rate", "median_intensity",
                "mean_ln1p", "mean_z"]]


def scaled_01(frame: pd.DataFrame, value: str = "mean_z", by: str = "protein_idx") -> pd.Series:
    """Min-max rescaling of a group mean across the plotted groups, per protein (the rule of the manuscript's marker dotplots)."""
    grp = frame.groupby(by)[value]
    lo, hi = grp.transform("min"), grp.transform("max")
    span = (hi - lo).where(hi > lo)
    return ((frame[value] - lo) / span).fillna(0.0)


def dotplot_table(summary: pd.DataFrame, rows: list[str], protein_idx: list[int]) -> pd.DataFrame:
    """Dotplot values for the given rows (groups) and proteins, in the given orders.

    Size = detection_rate; colour = mean_z rescaled 0-1 per protein across ``rows``.
    """
    sub = summary[summary["group"].isin(rows) & summary["protein_idx"].isin(protein_idx)].copy()
    sub["scaled_0_1"] = scaled_01(sub)
    sub["row_position"] = sub["group"].map({r: i for i, r in enumerate(rows)})
    col_pos = {}
    for i, p in enumerate(protein_idx):
        col_pos.setdefault(p, i)
    sub["column_position"] = sub["protein_idx"].map(col_pos)
    return sub.sort_values(["row_position", "column_position"]).reset_index(drop=True)


def protein_vector(values: pd.DataFrame, protein_idx: int, n_cells: int) -> np.ndarray:
    """Intensity of one protein in every cell (NaN = not detected)."""
    out = np.full(n_cells, np.nan)
    sub = values[values["protein_idx"] == protein_idx]
    out[sub["cell_idx"].to_numpy()] = sub["intensity"].to_numpy(dtype=np.float64)
    return out


def core_unique(summary: pd.DataFrame, groups: list[str], chosen: str, core_frac: float,
                unique_max_pct: float) -> tuple[np.ndarray, np.ndarray, int]:
    """Core and Unique protein indices for one group (rules of the first version of the browser).

    Core: detection rate >= ``core_frac`` in ``chosen``. Unique: Core proteins
    that reach the same threshold in <= ``unique_max_pct`` % of the other
    ``groups``. Returns (core, unique, number of other groups).
    """
    sub = summary[summary["group"].isin(groups)]
    present = sub[sub["detection_rate"] >= core_frac]
    core = np.sort(present.loc[present["group"] == chosen, "protein_idx"].unique())
    others = [g for g in groups if g != chosen]
    if not others:
        return core, core, 0
    n_other = (present[present["group"].isin(others)].groupby("protein_idx")["group"].nunique()
               .reindex(core, fill_value=0))
    unique = core[(n_other.to_numpy() / len(others) * 100.0) <= float(unique_max_pct)]
    return core, unique, len(others)


def detected_summary(values: pd.DataFrame, cell_mask: np.ndarray, n_proteins: int) -> pd.DataFrame:
    """Per protein, over the cells in ``cell_mask`` (bool per cell_idx): the number of cells with the
    protein detected, and the median and mean of ln(1 + intensity) among those cells (NaN without detections).

    Row position = protein_idx. Used by the comparison of two conditions.
    """
    v = values[np.asarray(cell_mask, dtype=bool)[values["cell_idx"].to_numpy()]]
    ln = pd.DataFrame({"p": v["protein_idx"].to_numpy(), "ln": np.log1p(v["intensity"].to_numpy(dtype=np.float64))})
    agg = ln.groupby("p", sort=False)["ln"].agg(["size", "median", "mean"]).reindex(np.arange(n_proteins))
    return pd.DataFrame({"n_detected": agg["size"].fillna(0).astype(np.int64).to_numpy(),
                         "median_ln1p_detected": agg["median"].to_numpy(),
                         "mean_ln1p_detected": agg["mean"].to_numpy()})


def dynamic_range_log10(intensity: np.ndarray) -> np.ndarray:
    """Per row: log10(max / min) over detected (> 0) entries; NaN without detections."""
    x = np.where(intensity > 0, intensity, np.nan)
    with warnings.catch_warnings(), np.errstate(invalid="ignore", divide="ignore"):
        warnings.simplefilter("ignore", RuntimeWarning)  # cells without detections -> NaN
        return np.log10(np.nanmax(x, axis=1) / np.nanmin(x, axis=1))
