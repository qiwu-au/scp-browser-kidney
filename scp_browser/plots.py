def overlay_values(values: np.ndarray, mode: str) -> np.ndarray:
    """Detected values of one protein as coloured by ``umap_overlay`` (ln(1 + intensity) or intensity)."""
    v = values[~np.isnan(values)]
    return np.log1p(v) if mode == "ln" else v


def umap_overlay(df: pd.DataFrame, values: np.ndarray, mode: str, clip_pct: float | None, xr, yr, size: int,
                 title: str, crange: tuple[float, float] | None = None) -> go.Figure:
    """Cells coloured by one protein; not-detected cells grey underneath.

    ``mode``: 'ln' = ln(1 + intensity), 'raw' = intensity, 'binary' = detected / not detected.
    ``crange``: fixed colour range (min, max), e.g. shared by two plots shown side by side; by default
    the range comes from the plotted values.
    """
    det = ~np.isnan(values)
    fig = go.Figure()
    miss = df.loc[~det]
    fig.add_trace(go.Scattergl(x=miss["UMAP1"], y=miss["UMAP2"], mode="markers", name="Not detected",
                               marker=dict(size=5, color=NOT_DETECTED), opacity=0.5, text=miss["hover"],
                               hovertemplate="%{text}<br>not detected<extra></extra>"))
    hit = df.loc[det]
    v = values[det]
    if mode == "binary":
        fig.add_trace(go.Scattergl(x=hit["UMAP1"], y=hit["UMAP2"], mode="markers", name="Detected",
                                   marker=dict(size=6, color="#256abf"), text=hit["hover"],
                                   hovertemplate="%{text}<br>detected<extra></extra>"))
    else:
        shown = np.log1p(v) if mode == "ln" else v
        cmax = float(np.percentile(shown, clip_pct)) if clip_pct and len(shown) else None
        cmin = float(np.min(shown)) if len(shown) else None
        cbar = "ln(1 + intensity)" if mode == "ln" else "intensity"
        order = np.argsort(shown)
        cbar_title = cbar + (f" (colour clipped at the {clip_pct:g}th percentile)" if cmax else "")
        if crange is not None:
            cmin, cmax = crange
        fig.add_trace(go.Scattergl(
            x=hit["UMAP1"].to_numpy()[order], y=hit["UMAP2"].to_numpy()[order], mode="markers", name="Detected",
            marker=dict(size=6, color=shown[order], colorscale="Viridis", cmin=cmin,
                        cmax=cmax, showscale=True,
                        colorbar=dict(orientation="h", x=0.5, xanchor="center", y=-0.14, yanchor="top", len=0.8,
                                      thickness=12, title=dict(text=cbar_title, side="top"))),
            text=hit["hover"].to_numpy()[order], customdata=v[order],
            hovertemplate="%{text}<br>intensity %{customdata:.4g}<extra></extra>"))
    fig.update_layout(title=title, legend=dict(orientation="h", x=1, xanchor="right", y=1.0, yanchor="bottom"))
    fig = _umap_axes(fig, xr, yr, size)
    fig.update_layout(margin=dict(l=10, r=10, t=60, b=90))
    return fig


def violin_by_group(df: pd.DataFrame, x: str, y: str, order: list[str], colors: dict[str, str], title: str,
                    y_label: str, log_y: bool = False, points: bool | str = False) -> go.Figure:
    fig = px.violin(df, x=x, y=y, color=x, box=True, points=points, category_orders={x: order},
                    color_discrete_map=colors, title=title, labels={x: "Cell type", y: y_label}, log_y=log_y)
    fig.update_layout(margin=MARGIN, template="plotly_white", legend_title_text=f"Cell type: {LEGEND_HINT}")
    return fig


def dotplot(table: pd.DataFrame, rows: list[str], columns: list[tuple[str, str]], title: str,
            column_groups: list[str] | None = None) -> go.Figure:
    """Size = fraction of cells detected; colour = group mean z rescaled 0-1 per protein.

    ``columns``: (column key, tick label) in plotting order; ``table`` has ``column_key``, ``group``,
    ``detection_rate``, ``scaled_0_1``, ``n_detected``, ``n_cells``, ``mean_ln1p``.
    """
    keys = [k for k, _ in columns]
    xpos = {k: i for i, k in enumerate(keys)}
    ypos = {r: i for i, r in enumerate(rows)}
    t = table[table["column_key"].isin(keys) & table["group"].isin(rows)].copy()
    t["x"] = t["column_key"].map(xpos)
    t["y"] = t["group"].map(ypos)
    max_px = 18
    sizes = np.sqrt(t["detection_rate"].clip(0, 1)) * max_px
    fig = go.Figure(go.Scatter(
        x=t["x"], y=t["y"], mode="markers",
        marker=dict(size=sizes.where(t["detection_rate"] > 0, 0), color=t["scaled_0_1"], colorscale=BLUE_SCALE,
                    cmin=0, cmax=1, line=dict(width=0.5, color="#9a9a9a"),
                    colorbar=dict(title="Mean (scaled 0–1<br>per protein)", len=0.45, y=1.0, yanchor="top")),
        customdata=np.stack([t["group"], t["tick"], t["detection_rate"], t["n_detected"], t["n_cells"],
                             t["mean_ln1p"]], axis=1),
        hovertemplate=("%{customdata[1]} in %{customdata[0]}<br>detected %{customdata[3]}/%{customdata[4]} "
                       "(%{customdata[2]:.0%})<br>mean ln(1+x) %{customdata[5]:.2f}<extra></extra>"),
        showlegend=False))
    for frac in (0.25, 0.5, 0.75, 1.0):
        fig.add_trace(go.Scatter(x=[None], y=[None], mode="markers", name=f"{frac:.0%}",
                                 marker=dict(size=np.sqrt(frac) * max_px, color="#9a9a9a"),
                                 legendgroup="size", showlegend=True))
    fig.update_xaxes(tickmode="array", tickvals=list(range(len(keys))), ticktext=[lbl for _, lbl in columns],
                     tickangle=-90, range=[-0.7, len(keys) - 0.3], showgrid=False, zeroline=False)
    fig.update_yaxes(tickmode="array", tickvals=list(range(len(rows))), ticktext=rows, autorange="reversed",
                     range=[len(rows) - 0.5, -0.5], showgrid=False, zeroline=False)
    if column_groups:
        start = 0
        for i in range(1, len(keys) + 1):
            if i == len(keys) or column_groups[i] != column_groups[start]:
                fig.add_shape(type="line", xref="x", yref="paper", x0=start - 0.35, x1=i - 1 + 0.35, y0=1.01, y1=1.01,
                              line=dict(color="#52514e", width=1))
                fig.add_annotation(x=(start + i - 1) / 2, y=1.02, xref="x", yref="paper", text=column_groups[start],
                                   showarrow=False, yanchor="bottom", font=dict(size=10), textangle=-45 if len(keys) > 30 else 0)
                start = i
    width_px = max(420, 26 * len(keys) + 220)
    fig.update_layout(title=title, template="plotly_white", height=max(320, 30 * len(rows) + 260),
                      width=width_px, margin=dict(l=10, r=10, t=110, b=10),
                      legend=dict(title="Fraction detected", orientation="v", x=1.02, y=0.0, yanchor="bottom"),
                      plot_bgcolor="white")
    return fig
